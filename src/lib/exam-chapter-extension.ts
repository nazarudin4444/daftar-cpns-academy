import type { Question, Subject } from "@/lib/exam";

const labels = ["A", "B", "C", "D", "E"] as const;
type Answer = (typeof labels)[number];

function makeQuestion(
  id: string,
  subject: Subject,
  prompt: string,
  options: [string, string, string, string, string],
  answer: Answer,
  explanation: string,
  tip: string,
): Question {
  return {
    id,
    subject,
    prompt,
    options: options.map((text, index) => ({ label: labels[index]!, text })),
    answer,
    explanation,
    tip,
    difficulty: id.includes("-hots-") ? "HOTS" : "Latihan",
  };
}

